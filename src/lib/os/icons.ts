/** the same bitmap as a standalone SVG (used to write public/favicon.svg) */
export function iconSvg(name: IconName): string {
  const rects = iconRects(name)
    .map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="1" fill="${RAW[BITMAPS[name][r.y][r.x]]}"/>`)
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">${rects}</svg>`;
}
