/** Row-run rects for one bitmap, merged horizontally so each icon is ~40 rects. */
export function iconRects(name: IconName) {
  const rows = BITMAPS[name];
  const out: { x: number; y: number; w: number; fill: string }[] = [];
  rows.forEach((row, y) => {
    if (row.length !== 16) throw new Error(`icon ${name} row ${y} is ${row.length} wide`);
    let x = 0;
    while (x < 16) {
      const c = row[x];
      let w = 1;
      while (x + w < 16 && row[x + w] === c) w++;
      if (c !== ".") out.push({ x, y, w, fill: FILL[c] });
      x += w;
    }
  });
  return out;
}

